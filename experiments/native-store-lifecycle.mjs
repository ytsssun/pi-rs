// Independent native binding lifecycle checks. No model calls.
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const assert=require('node:assert/strict');
const {Worker}=require('node:worker_threads');
const {once}=require('node:events');
const {mkdtempSync,rmSync}=require('node:fs');
const {tmpdir}=require('node:os');
const {join,resolve}=require('node:path');
const modulePath=resolve('target/native-session.node');
const binding=require(modulePath);
const rpc=r=>JSON.parse(binding.request(JSON.stringify(r)));
const root=mkdtempSync(join(tmpdir(),'native-store-review-'));
const header={type:'session',version:3,id:'review',cwd:root,timestamp:'2026-01-01T00:00:00.000Z'};
const workers=[];
const deadline=setTimeout(()=>{console.error('native lifecycle deadline exceeded');process.exit(2);},15000);
const create=i=>rpc({op:'create',path:join(root,String(i)),header}).result;
(async()=>{try{
assert.equal(rpc({op:'count'}).result,0);
for(const value of [undefined,null,4,{},Symbol('x')])assert.throws(()=>binding.request(value));
for(const value of ['{','null','[]','true'])assert.ok(JSON.parse(binding.request(value)).error);
assert.equal(rpc({op:'count'}).result,0);
assert.ok(rpc({op:'open',path:join(root,'missing')}).error);
assert.equal(rpc({op:'count'}).result,0);
const a=create('a'),b=create('b'); assert.notEqual(a,b);
assert.ok(rpc({op:'append',handle:a,entry:{type:'custom',customType:'a',data:{text:'😀\u0000'},id:'one',timestamp:header.timestamp}}).result);
assert.equal(rpc({op:'snapshot',handle:a}).result.entries.length,1);
assert.equal(rpc({op:'snapshot',handle:b}).result.entries.length,0);
assert.equal(rpc({op:'close',handle:a}).result,null);
const c=create('c'); assert.notEqual(a,c);
assert.ok(rpc({op:'snapshot',handle:a}).error);
assert.ok(rpc({op:'close',handle:a}).error);
const beforeCleanup=rpc({op:"diagnostics"}).result;
const worker=new Worker(`const {parentPort,workerData}=require('node:worker_threads'); const b=require(workerData.modulePath); const q=r=>JSON.parse(b.request(JSON.stringify(r))); const own=q({op:'create',path:workerData.path,header:workerData.header}).result; parentPort.postMessage({own,foreign:q({op:'snapshot',handle:workerData.foreign}),count:q({op:'count'}).result});`,{eval:true,workerData:{modulePath,path:join(root,'worker'),header,foreign:b}});
workers.push(worker);
const exit=once(worker,'exit');const [report]=await once(worker,'message');assert.ok(report.foreign.error);assert.equal(report.count,1);assert.ok(rpc({op:'snapshot',handle:report.own}).error);assert.equal((await exit)[0],0);
assert.deepEqual(rpc({op:'diagnostics'}).result,{finalizedEnvironments:beforeCleanup.finalizedEnvironments+1,abandonedStoresDropped:beforeCleanup.abandonedStoresDropped+1});
const terminated=new Worker(`const {parentPort,workerData}=require('node:worker_threads');const b=require(workerData.modulePath);const r=JSON.parse(b.request(JSON.stringify({op:'create',path:workerData.path,header:workerData.header})));if(r.error)throw Error(r.error);parentPort.postMessage('ready');setInterval(()=>{},1000);`,{eval:true,workerData:{modulePath,path:join(root,'terminated'),header}});
workers.push(terminated);
await once(terminated,'message');assert.equal(await terminated.terminate(),1);
assert.deepEqual(rpc({op:'diagnostics'}).result,{finalizedEnvironments:beforeCleanup.finalizedEnvironments+2,abandonedStoresDropped:beforeCleanup.abandonedStoresDropped+2});
assert.equal(rpc({op:'count'}).result,2);
const batch=Array.from({length:64},(_,i)=>create('batch'+i));assert.equal(rpc({op:'count'}).result,66);
for(const handle of [b,c,...batch])assert.equal(rpc({op:'close',handle}).result,null);
assert.equal(rpc({op:'count'}).result,0);
console.log(JSON.stringify({invalidInputsRejected:true,failedOpenDoesNotAllocate:true,isolatedStores:true,staleHandleRejected:true,crossWorkerHandlesRejected:true,workerNaturalExitWithOpenStore:0,workerTerminationExit:1,cleanupDelta:{finalizedEnvironments:2,abandonedStoresDropped:2},boundedCreateClose64:true,finalCount:0,limits:['Registry Drop counters verify cleanup entry and retained stores; not an allocator leak check or GC lifetime proof','No arbitrary registry maximum required or tested']},null,2));
}finally{await Promise.allSettled(workers.map(worker=>worker.terminate()));clearTimeout(deadline);rmSync(root,{recursive:true,force:true});}})().catch(e=>{console.error(e);process.exitCode=1;});
